let currentLang = localStorage.getItem("haras_lang") || "en";

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("haras_lang", lang);
  document.documentElement.lang = lang;

  // Traducir textos
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Traducir placeholders de inputs y textareas
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Actualizar etiqueta del botón de idioma
  const langLabel = document.getElementById("currentLangLabel");
  if (langLabel) {
    langLabel.textContent = lang === "en" ? "ES" : "EN";
  }
}

document.addEventListener("DOMContentLoaded", () => {
  setLanguage(currentLang);

  const toggleBtn = document.getElementById("langToggleBtn");
  if (toggleBtn) {
    toggleBtn.addEventListener("click", () => {
      const nextLang = currentLang === "en" ? "es" : "en";
      setLanguage(nextLang);
    });
  }
});